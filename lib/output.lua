local OUTPUT = "classpath.lua"

local function quote(text)
  return '"' .. text:gsub("\\", "\\\\"):gsub('"', '\\"') .. '"'
end

--[[ Lua rather than TOML, and the difference is not cosmetic. A TOML fragment
     has to be PASTED into daukle.toml, which mixes generated rows into the one
     file the user writes by hand. A Lua fragment in daukle/<toolchain>/ is
     loaded by core itself, so the generated pins stay in a file of their own
     that nobody is ever asked to edit or include, and the user's manifest keeps
     only what the user wrote. It APPENDS rather than assigns, so a hand-written
     classpath entry in daukle.toml survives beside the resolved ones. ]]
local function append_entries(lines, block, name, field, indent)
  if block.note ~= nil then
    for index = 1, #block.note do lines[#lines + 1] = indent .. "-- " .. block.note[index] end
  end
  lines[#lines + 1] = indent .. "local " .. name .. " = " .. field .. " or {}"
  lines[#lines + 1] = ""
  for index = 1, #block.entries do
    local entry = block.entries[index]
    lines[#lines + 1] = indent .. name .. "[#" .. name .. " + 1] = {"
    lines[#lines + 1] = indent .. "  url = " .. quote(entry.url) .. ","
    lines[#lines + 1] = indent .. "  sha256 = " .. quote(entry.sha256) .. ","
    lines[#lines + 1] = indent .. "  as = " .. quote(entry.artifact .. " " .. entry.version) .. ","
    lines[#lines + 1] = indent .. "}"
  end
  lines[#lines + 1] = ""
  lines[#lines + 1] = indent .. field .. " = " .. name
end

--- @implNote a nested path gets a `do` block of its own, so its `owner` walk
--- and its local cannot shadow the flat blocks around it. Its keys are quoted
--- fields and its local is always `pins`, so no key, "owner" included, can
--- collide with a name the block itself uses.
local function append_block(lines, block)
  local key = block.path[#block.path]
  if #block.path == 1 then
    append_entries(lines, block, key, "toolchain." .. key, "  ")
  else
    lines[#lines + 1] = "  do"
    lines[#lines + 1] = "    local owner = toolchain"
    for index = 1, #block.path - 1 do
      local step = "owner[" .. quote(block.path[index]) .. "]"
      lines[#lines + 1] = "    " .. step .. " = " .. step .. " or {}"
      lines[#lines + 1] = "    owner = " .. step
    end
    append_entries(lines, block, "pins", "owner[" .. quote(key) .. "]", "    ")
    lines[#lines + 1] = "  end"
  end
  lines[#lines + 1] = ""
end

--[[ One scope per target toolchain, with no special case for there being only
     one. A renderer that modelled exactly one target is the shape D-111 found
     wrong everywhere else in this org, and the cost of the uniform form is one
     indent in a file nobody edits by hand. A scope whose toolchain the manifest
     no longer declares does nothing: core loads this file on every command, so
     raising would fail the resolve that rewrites it too (D-201). ]]
local function append_target(lines, group)
  local key = group.target
  lines[#lines + 1] = "do"
  lines[#lines + 1] = "  local toolchain = daukle.config.toolchains and daukle.config.toolchains."
                      .. key
  lines[#lines + 1] = "  if toolchain ~= nil then"
  local body = {}
  for index = 1, #group.blocks do append_block(body, group.blocks[index]) end
  body[#body] = nil
  for index = 1, #body do
    lines[#lines + 1] = body[index] == "" and "" or "  " .. body[index]
  end
  lines[#lines + 1] = "  end"
  lines[#lines + 1] = "end"
  lines[#lines + 1] = ""
end

local GENERATED_HEADER = "-- Generated by maven:resolve. Do not edit: daukle.toml is yours, this is not."

--- @param header optional first comment line, naming the writer when it is not maven:resolve
local function render(groups, header)
  local lines = {
    header or GENERATED_HEADER,
    "-- Loaded by daukle itself: no daukle.lua line is needed.",
    "",
  }
  for index = 1, #groups do append_target(lines, groups[index]) end
  return table.concat(lines, "\n")
end

return {
  OUTPUT = OUTPUT,
  render = render,
}
